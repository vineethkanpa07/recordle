# ---------------------------------------------------------------- SQLite (your computer)

def _sqlite_columns(conn, table):
    return {row[1] for row in conn.execute(f"PRAGMA table_info({table})")}


def _init_sqlite(path):
    with sqlite3.connect(path) as conn:
        existing = {r[0] for r in conn.execute("SELECT name FROM sqlite_master WHERE type = 'table'")}
        # Databases from the single-user version have no user_id columns. Upgrade them in place;
        # their albums are handed to the first account that signs up.
        if "artists" in existing and "user_id" not in _sqlite_columns(conn, "artists"):
            # Build the new table beside the old one, then swap names, so the albums table's
            # link to "artists" keeps pointing at the right table.
            conn.executescript("""
                PRAGMA foreign_keys = OFF;
                CREATE TABLE artists_new (
                    id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER REFERENCES users(id),
                    name TEXT NOT NULL, key TEXT NOT NULL, position INTEGER NOT NULL DEFAULT 0,
                    UNIQUE (user_id, key));
                INSERT INTO artists_new (id, user_id, name, key, position)
                    SELECT id, NULL, name, key, position FROM artists;
                DROP TABLE artists;
                ALTER TABLE artists_new RENAME TO artists;
            """)
        if "albums" in existing and "user_id" not in _sqlite_columns(conn, "albums"):
            conn.execute("ALTER TABLE albums ADD COLUMN user_id INTEGER REFERENCES users(id)")
        conn.executescript(SQLITE_SCHEMA)
        if "top_song_id" not in _sqlite_columns(conn, "albums"):
            conn.execute("ALTER TABLE albums ADD COLUMN top_song_id INTEGER")
        if "itunes_id" not in _sqlite_columns(conn, "albums"):
            conn.execute("ALTER TABLE albums ADD COLUMN itunes_id INTEGER")
        if "year" not in _sqlite_columns(conn, "albums"):
            conn.execute("ALTER TABLE albums ADD COLUMN year INTEGER")
        if "rated_at" not in _sqlite_columns(conn, "albums"):
            conn.execute("ALTER TABLE albums ADD COLUMN rated_at REAL")
        if "released" not in _sqlite_columns(conn, "albums"):
            conn.execute("ALTER TABLE albums ADD COLUMN released TEXT")


def _connect_sqlite(path):
    conn = sqlite3.connect(path)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    return conn


# ---------------------------------------------------------------- Postgres (hosting)

class Row(dict):
    """A result row usable like sqlite3.Row: row["name"], row[0] and dict(row) all work."""

    def __getitem__(self, key):
        if isinstance(key, int):
            return list(self.values())[key]
        return super().__getitem__(key)


def _row_factory(cursor):
    names = [c.name for c in cursor.description] if cursor.description else []
    return lambda values: Row(zip(names, values))


class _PgResult:
    def __init__(self, cursor, lastrowid=None):
        self._cursor, self.lastrowid = cursor, lastrowid

    def fetchone(self):
        return self._cursor.fetchone()

    def fetchall(self):
        return self._cursor.fetchall()

    def __iter__(self):
        return iter(self._cursor)


class _PgConnection:
    """Wraps a pooled psycopg connection so SQLite-style queries run unchanged."""

    def __init__(self, raw):
        self.raw = raw

    @staticmethod
    def _sql(sql):
        return sql.replace("?", "%s")

    def execute(self, sql, params=()):
        sql = self._sql(sql)
        wants_id = sql.lstrip().upper().startswith("INSERT") and "RETURNING" not in sql.upper()
        if wants_id:
            sql += " RETURNING id"
        cur = self.raw.cursor()
        cur.execute(sql, params)
        return _PgResult(cur, cur.fetchone()["id"] if wants_id else None)

    def executemany(self, sql, seq):
        self.raw.cursor().executemany(self._sql(sql), seq)

    def commit(self):
        self.raw.commit()


_pool = None


def _get_pool():
    global _pool
    if _pool is None:
        from psycopg_pool import ConnectionPool
        # Small pool: free databases allow few connections. min_size=0 and max_idle close
        # connections after a minute of no use, so a free Neon database can go to sleep (it only
        # counts compute time while awake). check= replaces connections the database closed.
        # prepare_threshold=None: Neon's pooled connections don't keep prepared statements between queries.
        _pool = ConnectionPool(DATABASE_URL, min_size=0, max_size=5, max_idle=60, timeout=CONNECT_TIMEOUT,
                               kwargs={"row_factory": _row_factory, "prepare_threshold": None, "connect_timeout": CONNECT_TIMEOUT},
                               check=ConnectionPool.check_connection, open=True)
    return _pool


def _getconn():
    from psycopg_pool import PoolTimeout
    try:
        return _get_pool().getconn()
    except PoolTimeout as err:
        raise DatabaseUnavailable(str(err)) from err


def _init_postgres():
    import psycopg
    try:
        with psycopg.connect(DATABASE_URL, connect_timeout=CONNECT_TIMEOUT, prepare_threshold=None) as conn:
            # Several web workers can start at once; the lock stops them creating tables at the same time.
            conn.execute("SELECT pg_advisory_xact_lock(727274)")
            conn.execute(POSTGRES_SCHEMA)
            # columns added after the first version, for databases made before them
            conn.execute("ALTER TABLE albums ADD COLUMN IF NOT EXISTS itunes_id BIGINT")
            conn.execute("ALTER TABLE albums ADD COLUMN IF NOT EXISTS year INTEGER")
            conn.execute("ALTER TABLE albums ADD COLUMN IF NOT EXISTS rated_at DOUBLE PRECISION")
            conn.execute("ALTER TABLE albums ADD COLUMN IF NOT EXISTS released TEXT")
        log("Connected to the database and checked its tables.")
    except psycopg.Error as err:
        # Keep the site up so the error page can explain the problem; the log says what went wrong.
        log(f"COULD NOT CONNECT TO THE DATABASE: {str(err).strip()}")
        log("Check DATABASE_URL in Render > your service > Environment. It should be Neon's connection string, "
            "starting with postgresql:// and ending with sslmode=require.")


# ---------------------------------------------------------------- what app.py uses

def init(sqlite_path):
    log(f"Storing data in: {describe_database()}")
    if USE_POSTGRES:
        _init_postgres()
    else:
        _init_sqlite(sqlite_path)


def connect(sqlite_path):
    """A connection for one request. Pass it to close() when the request ends."""
    if USE_POSTGRES:
        return _PgConnection(_getconn())
    return _connect_sqlite(sqlite_path)


def close(conn):
    if isinstance(conn, _PgConnection):
        conn.raw.rollback()  # drop anything left uncommitted (a request that failed part-way)
        _get_pool().putconn(conn.raw)
    else:
        conn.close()
